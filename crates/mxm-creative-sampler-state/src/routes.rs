/// The group a host lists every route parameter under: the plugin's `#[nested(group = …)]`.
pub const GROUP: &str = "Modulation";

/// What a route reads: **what its pair delivers at this amount, in the target's own unit** —
/// `plans/plan-modulation-routing.md` decision 1.11. A percentage of the amplifier's level,
/// octaves on the cutoff, semitones on the pitch, a rate against the source's own on Scan speed
/// (the unit its knob reads in), and per octave of keyboard for a Key route. So the retired
/// controls' routes read, at full, the reaches they had: `+100 %` from Velocity — velocity
/// sensitivity at full, the knob it replaced — `+4.00 oct` from the Envelope, `+2.00 oct` from
/// Pressure, `+0.60x` and `-0.47x` from LFO 1; and every other route the collection's standard
/// reach, `+12.00 st/oct` from Key on the pitch among them.
#[must_use]
pub fn reach(target: usize, source: usize) -> Reach {
    let unit = match target {
        target::AMPLITUDE => text::PERCENT,
        target::CUTOFF => text::OCTAVES,
        target::PITCH => text::SEMITONES,
        _ => text::TIMES,
    };
    let full = FULL_SCALE[target][source];
    if source == source::KEY {
        Reach::per_octave(full * 12.0 / KEY_UNIT_SEMITONES, unit)
    } else {
        Reach::new(full, unit)
    }
}

/// How a pair's amount travels: **signed and drawn bipolar**, because its centre is *no
/// modulation*, on the halves the modulation standard offers it.
#[must_use]
pub fn fader(target: usize, source: usize) -> Fader {
    Fader::for_offer(offer(target, source), false)
}

/// *"Cutoff from Velocity"* — the target first, because that is the control the row belongs to.
#[must_use]
pub fn presence_name(target: usize, source: usize) -> String {
    format!("{} from {}", TARGET_NAMES[target], SOURCE_NAMES[source])
}

/// *"Cutoff from Velocity amount"*.
#[must_use]
pub fn amount_name(target: usize, source: usize) -> String {
    format!(
        "{} from {} amount",
        TARGET_NAMES[target], SOURCE_NAMES[source]
    )
}
