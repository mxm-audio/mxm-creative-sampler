//! # The ids are mechanically derived, and still provisional
//!
//! One `#[nested(id_prefix = …)]` per target in the plugin, so a pair's id is `<target>_<source>`
//! and `<target>_<source>on`. Never typed by hand, so no instrument's routing ids can drift from
//! another's. **Provisional like every id in this plugin** — its own contract says so until the S3
//! gate — so the derivation is what stops them drifting rather than a promise of permanence this
//! plugin has not yet made.

